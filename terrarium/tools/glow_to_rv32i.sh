#!/bin/sh
# glow_to_rv32i.sh -- Orbit 11 minimal Glow-to-RV32I code generator
#
# Reads a .glow source, extracts a constant numeric value from a
# simple expression, and emits RV32I assembly that prints the value
# to UART and exits via the sifive test finisher.
#
# Usage: sh terrarium/tools/glow_to_rv32i.sh <input.glow> <output.S>
#
# Exit codes match glow_run.rye: 0=ok, 2=declined, 3=unreadable, 4=usage

set -e

if [ $# -lt 2 ]; then
    echo "usage: glow_to_rv32i.sh <input.glow> <output.S>" >&2
    exit 4
fi

INPUT="$1"
OUTPUT="$2"

if [ ! -f "$INPUT" ]; then
    echo "error: $INPUT not found" >&2
    exit 3
fi

# Strip :: comments and blank lines, collect the expression.
EXPR=$(sed 's/::.*$//' "$INPUT" | tr -s ' ' | sed '/^[[:space:]]*$/d')

# Extract the last bare integer from the expression.
# Handles: ^- @u32 42, =/ name=@u32 ^- @u32 42, bare 42
VALUE=$(echo "$EXPR" | grep -oE '[0-9]+' | tail -1)

if [ -z "$VALUE" ]; then
    echo "error: no numeric literal found in $INPUT" >&2
    exit 2
fi

echo "glow_to_rv32i: $INPUT -> $OUTPUT (value=$VALUE)"

cat > "$OUTPUT" << 'HEADER'
# Generated by glow_to_rv32i.sh -- Glow-to-RV32I backend
# Do not edit; regenerate from the .glow source.

    .section .text.init
    .globl _start

_start:
    li      sp, 0x80100000
    jal     main
    # exit via sifive test finisher
    li      t0, 0x00100000
    li      t1, 0x5555
    sw      t1, 0(t0)
1:  j       1b

main:
    addi    sp, sp, -16
    sw      ra, 12(sp)
HEADER

# Emit the value load and call to print_u32.
cat >> "$OUTPUT" << EOF
    li      a0, $VALUE
EOF

cat >> "$OUTPUT" << 'TAIL'
    jal     print_u32
    lw      ra, 12(sp)
    addi    sp, sp, 16
    ret

# print_u32 -- print a0 as unsigned decimal to UART
# RV32I base has no div; uses repeated subtraction.
print_u32:
    addi    sp, sp, -48
    sw      ra, 44(sp)
    mv      t6, sp
    li      t5, 0
    bnez    a0, .Lnonzero
    li      a0, 48
    jal     uart_putc
    j       .Lprint_done
.Lnonzero:
.Ldiv_loop:
    beqz    a0, .Lprint_digits
    # a0 / 10 by repeated subtraction
    mv      t1, a0
    li      t2, 10
    li      t0, 0
.Lsub_loop:
    blt     t1, t2, .Lsub_done
    sub     t1, t1, t2
    addi    t0, t0, 1
    j       .Lsub_loop
.Lsub_done:
    # t0 = quotient, t1 = remainder
    addi    t1, t1, 48
    sb      t1, 0(t6)
    addi    t6, t6, 1
    addi    t5, t5, 1
    mv      a0, t0
    j       .Ldiv_loop
.Lprint_digits:
    addi    t6, t6, -1
.Ldigit_loop:
    blt     t6, sp, .Lprint_done
    lb      a0, 0(t6)
    jal     uart_putc
    addi    t6, t6, -1
    j       .Ldigit_loop
.Lprint_done:
    li      a0, 10
    jal     uart_putc
    lw      ra, 44(sp)
    addi    sp, sp, 48
    ret

# uart_putc -- write byte in a0 to UART THR at 0x10000000
uart_putc:
    li      t0, 0x10000000
    sb      a0, 0(t0)
    ret
TAIL

echo "glow_to_rv32i: wrote $OUTPUT"
