#!/bin/sh
# glow_to_rv32i.sh -- Glow-to-RV32I code generator
#
# Reads a .glow source, compiles it to RV32I assembly that prints
# the result to UART and exits via the sifive test finisher.
#
# Supported Glow forms:
#   ^-  @u32  <N>           -- cast literal
#   =/  <name>  <N>         -- face binding (variable = literal)
#   %-  <op>  <name>        -- stdlib call (double, inc, dec,
#                              square, half, negate)
#   ?:  (gth <a> <b>) T F   -- conditional (greater-than)
#   /+  <lib>               -- library import (ignored)
#   bare <N>                -- literal integer
#
# Usage: sh terrarium/tools/glow_to_rv32i.sh <input.glow> <output.S>
#
# Exit codes: 0=ok, 2=declined, 3=unreadable, 4=usage

set -e

if [ $# -lt 2 ]; then
    echo "usage: glow_to_rv32i.sh <input.glow> <output.S>" >&2
    exit 4
fi

INPUT="$1"
OUTPUT="$2"

if [ ! -f "$INPUT" ]; then
    echo "error: $INPUT not found" >&2
    exit 3
fi

# Strip :: comments and blank lines.
CLEAN=$(sed 's/::.*$//' "$INPUT" | sed '/^[[:space:]]*$/d')

# Parse the source into an intermediate representation.
rm -f "$OUTPUT.parse"
echo "$CLEAN" | while IFS= read -r line; do
    line=$(echo "$line" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')
    [ -z "$line" ] && continue
    rune=$(echo "$line" | awk '{print $1}')
    case "$rune" in
        "/+") ;;
        "=/")
            name=$(echo "$line" | awk '{print $2}')
            val=$(echo "$line" | awk '{print $3}')
            echo "FACE $name $val" >> "$OUTPUT.parse"
            ;;
        "%-")
            op=$(echo "$line" | awk '{print $2}')
            arg=$(echo "$line" | awk '{print $3}')
            echo "CALL $op $arg" >> "$OUTPUT.parse"
            ;;
        "^-")
            val=$(echo "$line" | awk '{print $3}')
            echo "LITERAL $val" >> "$OUTPUT.parse"
            ;;
        "?:")
            rest=$(echo "$line" | sed 's/^?:[[:space:]]*//')
            cmp_fn=$(echo "$rest" | sed 's/.*(\([a-z]*\).*/\1/')
            cmp_a=$(echo "$rest" \
                | sed 's/.*([a-z]* \([^ )]*\).*/\1/')
            cmp_b=$(echo "$rest" \
                | sed 's/.*([a-z]* [^ )]* \([^ )]*\)).*/\1/')
            then_val=$(echo "$rest" \
                | sed 's/.*)[[:space:]]*//' | awk '{print $1}')
            else_val=$(echo "$rest" \
                | sed 's/.*)[[:space:]]*//' | awk '{print $2}')
            echo "COND $cmp_fn $cmp_a $cmp_b $then_val $else_val" \
                >> "$OUTPUT.parse"
            ;;
        *)
            if echo "$rune" | grep -qE '^[0-9]+$'; then
                echo "LITERAL $rune" >> "$OUTPUT.parse"
            fi
            ;;
    esac
done

if [ ! -f "$OUTPUT.parse" ]; then
    echo "error: no expressions found in $INPUT" >&2
    exit 2
fi

echo "glow_to_rv32i: $INPUT -> $OUTPUT"

# Emit the assembly preamble.
cat > "$OUTPUT" << 'HEADER'
# Generated by glow_to_rv32i.sh -- Glow-to-RV32I backend
# Do not edit; regenerate from the .glow source.

    .section .text.init
    .globl _start

_start:
    li      sp, 0x80100000
    jal     main
    # exit via sifive test finisher
    li      t0, 0x00100000
    li      t1, 0x5555
    sw      t1, 0(t0)
1:  j       1b

main:
    addi    sp, sp, -16
    sw      ra, 12(sp)
HEADER

# Walk the IR and emit main body.
: > "$OUTPUT.syms"
COND_ID=0

while IFS= read -r ir; do
    tag=$(echo "$ir" | awk '{print $1}')
    case "$tag" in
        FACE)
            name=$(echo "$ir" | awk '{print $2}')
            val=$(echo "$ir" | awk '{print $3}')
            echo "$name=$val" >> "$OUTPUT.syms"
            ;;
        LITERAL)
            val=$(echo "$ir" | awk '{print $2}')
            cat >> "$OUTPUT" << EOF
    li      a0, $val
EOF
            ;;
        CALL)
            op=$(echo "$ir" | awk '{print $2}')
            arg=$(echo "$ir" | awk '{print $3}')
            resolved=$(grep "^${arg}=" "$OUTPUT.syms" \
                | tail -1 | cut -d= -f2)
            [ -z "$resolved" ] && resolved="$arg"
            cat >> "$OUTPUT" << EOF
    li      a0, $resolved
EOF
            case "$op" in
                double)
                    cat >> "$OUTPUT" << 'EOF'
    slli    a0, a0, 1
EOF
                    ;;
                inc)
                    cat >> "$OUTPUT" << 'EOF'
    addi    a0, a0, 1
EOF
                    ;;
                dec)
                    cat >> "$OUTPUT" << 'EOF'
    addi    a0, a0, -1
EOF
                    ;;
                square)
                    cat >> "$OUTPUT" << 'EOF'
    mv      a1, a0
    jal     multiply
EOF
                    ;;
                half)
                    cat >> "$OUTPUT" << 'EOF'
    srli    a0, a0, 1
EOF
                    ;;
                negate)
                    cat >> "$OUTPUT" << 'EOF'
    neg     a0, a0
EOF
                    ;;
                *)
                    echo "error: unknown op $op" >&2
                    rm -f "$OUTPUT.parse" "$OUTPUT.syms"
                    exit 2
                    ;;
            esac
            ;;
        COND)
            cmp_fn=$(echo "$ir" | awk '{print $2}')
            cmp_a=$(echo "$ir" | awk '{print $3}')
            cmp_b=$(echo "$ir" | awk '{print $4}')
            then_val=$(echo "$ir" | awk '{print $5}')
            else_val=$(echo "$ir" | awk '{print $6}')
            res_a=$(grep "^${cmp_a}=" "$OUTPUT.syms" \
                | tail -1 | cut -d= -f2)
            [ -z "$res_a" ] && res_a="$cmp_a"
            res_b=$(grep "^${cmp_b}=" "$OUTPUT.syms" \
                | tail -1 | cut -d= -f2)
            [ -z "$res_b" ] && res_b="$cmp_b"
            cat >> "$OUTPUT" << EOF
    li      t0, $res_a
    li      t1, $res_b
EOF
            case "$cmp_fn" in
                gth)
                    cat >> "$OUTPUT" << EOF
    ble     t0, t1, .Lelse_$COND_ID
    li      a0, $then_val
    j       .Lend_$COND_ID
.Lelse_$COND_ID:
    li      a0, $else_val
.Lend_$COND_ID:
EOF
                    ;;
                *)
                    echo "error: unknown cmp $cmp_fn" >&2
                    rm -f "$OUTPUT.parse" "$OUTPUT.syms"
                    exit 2
                    ;;
            esac
            COND_ID=$((COND_ID + 1))
            ;;
    esac
done < "$OUTPUT.parse"

# Emit print call, epilogue, and runtime functions.
cat >> "$OUTPUT" << 'TAIL'
    jal     print_u32
    lw      ra, 12(sp)
    addi    sp, sp, 16
    ret

# multiply -- a0 = a0 * a1 (unsigned, by repeated addition)
# RV32I base has no mul instruction.
multiply:
    mv      t0, a0
    li      a0, 0
    beqz    t0, .Lmul_done
.Lmul_loop:
    add     a0, a0, a1
    addi    t0, t0, -1
    bnez    t0, .Lmul_loop
.Lmul_done:
    ret

# print_u32 -- print a0 as unsigned decimal to UART
# Uses bltu (unsigned) so values above 2^31 print correctly.
# RV32I base has no div; uses repeated subtraction.
print_u32:
    addi    sp, sp, -48
    sw      ra, 44(sp)
    mv      t6, sp
    li      t5, 0
    bnez    a0, .Lnonzero
    li      a0, 48
    jal     uart_putc
    j       .Lprint_done
.Lnonzero:
.Ldiv_loop:
    beqz    a0, .Lprint_digits
    # unsigned a0 / 10 by repeated subtraction
    mv      t1, a0
    li      t2, 10
    li      t0, 0
.Lsub_loop:
    bltu    t1, t2, .Lsub_done
    sub     t1, t1, t2
    addi    t0, t0, 1
    j       .Lsub_loop
.Lsub_done:
    # t0 = quotient, t1 = remainder
    addi    t1, t1, 48
    sb      t1, 0(t6)
    addi    t6, t6, 1
    addi    t5, t5, 1
    mv      a0, t0
    j       .Ldiv_loop
.Lprint_digits:
    addi    t6, t6, -1
.Ldigit_loop:
    blt     t6, sp, .Lprint_done
    lb      a0, 0(t6)
    jal     uart_putc
    addi    t6, t6, -1
    j       .Ldigit_loop
.Lprint_done:
    li      a0, 10
    jal     uart_putc
    lw      ra, 44(sp)
    addi    sp, sp, 48
    ret

# uart_putc -- write byte in a0 to UART THR at 0x10000000
uart_putc:
    li      t0, 0x10000000
    sb      a0, 0(t0)
    ret
TAIL

rm -f "$OUTPUT.parse" "$OUTPUT.syms"
echo "glow_to_rv32i: wrote $OUTPUT"
